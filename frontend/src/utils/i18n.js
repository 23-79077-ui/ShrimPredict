// Case-insensitive lookup map for natural phrases
const phraseMapFilLower = Object.keys(phraseMapFil).reduce((acc, k) => {
  acc[k.toLowerCase().trim()] = phraseMapFil[k];
  return acc;
}, {});

/**
 * Robust phrase lookup for Filipino: handles exact, trimmed, case-insensitive,
 * and punctuation differences (colons, ellipses).
 */
const lookupFilipinoPhrase = (str) => {
  if (!str || typeof str !== 'string') return null;
  const trimmed = str.trim();
  if (phraseMapFil[str] !== undefined) return phraseMapFil[str];
  if (phraseMapFil[trimmed] !== undefined) return phraseMapFil[trimmed];

  const lower = trimmed.toLowerCase();
  if (phraseMapFilLower[lower] !== undefined) return phraseMapFilLower[lower];

  // If ends with colon e.g. "Total Feed:"
  if (trimmed.endsWith(':')) {
    const withoutColon = trimmed.slice(0, -1).trim();
    if (phraseMapFil[withoutColon] !== undefined) return phraseMapFil[withoutColon] + ':';
    if (phraseMapFilLower[withoutColon.toLowerCase()] !== undefined) return phraseMapFilLower[withoutColon.toLowerCase()] + ':';
  }

  // If ends with ellipsis e.g. "Search pond..." or "..."
  if (trimmed.endsWith('...') || trimmed.endsWith('…')) {
    const withoutEllipsis = trimmed.replace(/\.{3}$|…$/, '').trim();
    if (phraseMapFil[withoutEllipsis] !== undefined) return phraseMapFil[withoutEllipsis] + '...';
    if (phraseMapFilLower[withoutEllipsis.toLowerCase()] !== undefined) return phraseMapFilLower[withoutEllipsis.toLowerCase()] + '...';
  }

  return null;
};

/**
 * Returns current language code ('en' or 'fil'). Defaults to 'en'.
 */
export const getLanguage = () => {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'fil' || saved === 'en') {
      return saved;
    }
  } catch (err) {
    console.warn('Unable to access localStorage for language:', err);
  }
  return 'en';
};

/**
 * Sets current language ('en' or 'fil') and notifies the entire application.
 *
 * @param {'en'|'fil'} lang
 */
export const setLanguage = (lang) => {
  const target = lang === 'fil' ? 'fil' : 'en';
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, target);
  } catch (err) {
    console.warn('Unable to save language in localStorage:', err);
  }

  // Set html lang attribute
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', target);
  }

  // Broadcast event across app
  if (typeof window !== 'undefined') {
    window.dispatchEvent(
      new CustomEvent('shrim-language-changed', {
        detail: {
          language: target,
        },
      })
    );
  }

  return target;
};

/**
 * Toggles between English and Filipino
 */
export const toggleLanguage = () => {
  const current = getLanguage();
  const next = current === 'en' ? 'fil' : 'en';
  return setLanguage(next);
};

/**
 * Translates a key or phrase.
 * If key matches structured dictionary key, returns translated value.
 * If key is a known English phrase and language is 'fil', returns Filipino translation.
 * Otherwise returns fallback or original key.
 *
 * @param {string} key
 * @param {string} [fallback]
 * @returns {string}
 */
export const t = (key, fallback = null) => {
  if (!key) return '';
  const currentLang = getLanguage();

  const dict = dictionaries[currentLang] || dictionaries.en;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }

  // In Filipino mode, check direct phrase map and fuzzy resolution
  if (currentLang === 'fil') {
    const directMatch = lookupFilipinoPhrase(key);
    if (directMatch !== null) {
      return directMatch;
    }
    if (fallback) {
      const fallbackMatch = lookupFilipinoPhrase(fallback);
      if (fallbackMatch !== null) {
        return fallbackMatch;
      }
    }
  }

  // Fallback to English dictionary if key was a dictionary key
  if (dictionaries.en[key] !== undefined) {
    return dictionaries.en[key];
  }

  return fallback !== null ? fallback : key;
};

